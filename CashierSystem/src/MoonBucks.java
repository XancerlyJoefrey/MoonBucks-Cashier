        StringBuilder summary = new StringBuilder();
        summary.append("=== MOONBUCKS SALES INVENTORY ===\n\n");
        
        for (Map.Entry<String, Integer> entry : salesInventory.entrySet()) {
            summary.append(String.format("%-18s : %d sold\n", entry.getKey(), entry.getValue()));
        }
        
        summary.append("\n=================================\n");
