    private void btnDoneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDoneActionPerformed
         try {
            double total = Double.parseDouble(txtTotal.getText());
            double cash = Double.parseDouble(txtCash.getText());

            if (cash < total) {
                JOptionPane.showMessageDialog(this, "Insufficient cash provided!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            double change = cash - total;
            txtChange.setText(String.format("%.2f", change));

            for (Map.Entry<String, Integer> entry : currentOrderItems.entrySet()) {
                String item = entry.getKey();
                int orderQty = entry.getValue();
                salesInventory.put(item, salesInventory.get(item) + orderQty);
            }
            
            lifetimeRevenue += total;
            JOptionPane.showMessageDialog(this, "Transaction completed successfully!");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric value for Cash.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDoneActionPerformed

